# PlatformIO pre-build script: derives the firmware version from git and writes
# it to include/version.h (generated, not tracked).
#
#   v1.1.0                   built exactly at tag v1.1.0
#   v1.1.0-4-g949e581        4 commits after the tag
#   v1.1.0-4-g949e581-dirty  with uncommitted changes
#
# A header, not a build flag: a changed define on the command line would
# recompile the whole project and all libraries for every commit.

import os
import subprocess

Import("env")

project_dir = env["PROJECT_DIR"]
header_path = os.path.join(project_dir, "include", "version.h")


def git_version():
    try:
        return subprocess.check_output(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=project_dir,
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"  # e.g. built from a source archive


header = (
    "// Generated by scripts/version.py, do not edit.\n"
    "#pragma once\n"
    '#define VERSIONSTR "{}"\n'.format(git_version())
)

previous = None
if os.path.exists(header_path):
    with open(header_path) as f:
        previous = f.read()

# Keep the timestamp when nothing changed, so nothing recompiles
if header != previous:
    with open(header_path, "w") as f:
        f.write(header)
